/**
 * Workspace manifest + path helpers.
 *
 * A Unity workspace is a *project directory*, not a single document: the
 * closest analogue to Blender's model.blend is the scene (.unity YAML file) plus
 * everything referenced from it. The manifest therefore records the project
 * root, the scene pi considers "the" scene, and the module/iteration history
 * the module runner needs to be able to revert.
 */

import { cpSync, existsSync, mkdirSync, readFileSync, readdirSync, renameSync, rmSync, statSync, writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";

import { getBundledUnityBridgeDir, getUnityTempDir } from "../config.js";
import { delay } from "./utils.js";

export const MANIFEST_FILE = "unity-workspace.json";
export const WORKSPACE_SCRIPT_FILE = "script.cs";
export const CRITIQUE_LOG_FILE = "critique.log";
export const BRIDGE_DIR_MARKER_FILE = "unity-bridge-dir.txt";
export const DEFAULT_SCENE_NAME = "Main.unity";
export const DEFAULT_RENDER_EXTENSION = ".png";
export const MANIFEST_VERSION = 2;

const MANIFEST_LOCK_STALE_MS = 30_000;

export interface SavedView {
	name: string;
	cameraName: string;
}

export interface ModuleRunRecord {
	name: string;
	iteration: number;
	checkpointPath: string;
	at: string;
	sequence: number;
	exitCode: number;
	status: "ok";
}

export interface UnityWorkspaceManifest {
	version: number;
	id: string;
	projectPath: string;
	scenePath: string;
	createdAt: string;
	updatedAt: string;
	latestIteration: number;
	moduleRuns: ModuleRunRecord[];
	savedViews: SavedView[];
	renderOutputs: string[];
	/** True when the project was adopted rather than generated by pi. */
	adopted: boolean;
}

export function nowIso(): string {
	return new Date().toISOString();
}

export function createWorkspaceId(): string {
	const stamp = new Date().toISOString().replace(/[-:]/g, "").replace(/\..+$/, "").replace("T", "_");
	return stamp;
}

export function getManifestPath(workspacePath: string): string {
	return join(workspacePath, MANIFEST_FILE);
}

export function getWorkspaceScriptPath(workspacePath: string): string {
	return join(workspacePath, WORKSPACE_SCRIPT_FILE);
}

export function getWorkspaceCritiqueLogPath(workspacePath: string): string {
	return join(workspacePath, CRITIQUE_LOG_FILE);
}

export function getIterationPaths(
	workspacePath: string,
	iteration: number,
): { iterationDir: string; rendersDir: string } {
	const iterationDir = join(workspacePath, `iteration_${String(iteration).padStart(2, "0")}`);
	return { iterationDir, rendersDir: join(iterationDir, "renders") };
}

export function fileExists(path: string): boolean {
	try {
		return statSync(path).isFile();
	} catch {
		return false;
	}
}

export function readManifest(manifestPath: string): UnityWorkspaceManifest {
	let raw: string;
	try {
		raw = readFileSync(manifestPath, "utf8");
	} catch {
		throw new Error(`Workspace manifest not found: ${manifestPath}`);
	}
	try {
		return JSON.parse(raw) as UnityWorkspaceManifest;
	} catch (error) {
		throw new Error(
			`Workspace manifest is not valid JSON: ${manifestPath}. ` +
				`It was probably written by a concurrent run, or hand-edited into an invalid state. ` +
				`Fix or delete it and retry. (${error instanceof Error ? error.message : String(error)})`,
		);
	}
}

function writeManifest(manifestPath: string, manifest: UnityWorkspaceManifest): void {
	manifest.version = MANIFEST_VERSION;
	manifest.updatedAt = nowIso();
	const temp = `${manifestPath}.${process.pid}.tmp`;
	writeFileSync(temp, `${JSON.stringify(manifest, undefined, 2)}\n`, "utf8");
	// Atomic publish: a reader must never see a half-written manifest.
	renameSync(temp, manifestPath);
}

interface ManifestLock {
	release: () => void;
}

/**
 * Serializes manifest read-modify-write. Never held while Unity runs, so it
 * cannot block real work — it exists because execute and module_run both read
 * `latestIteration` and would otherwise claim the same iteration number.
 */
async function acquireManifestLock(
	workspacePath: string,
	options?: { signal?: AbortSignal; timeoutMs?: number },
): Promise<ManifestLock> {
	const lockPath = join(workspacePath, ".manifest.lock");
	const deadline = Date.now() + (options?.timeoutMs ?? MANIFEST_LOCK_STALE_MS);

	for (;;) {
		try {
			writeFileSync(lockPath, JSON.stringify({ pid: process.pid, acquiredAt: nowIso() }), { flag: "wx" });
			return {
				release: () => {
					try {
						rmSync(lockPath, { force: true });
					} catch {
						/* already gone */
					}
				},
			};
		} catch (error) {
			if ((error as NodeJS.ErrnoException).code !== "EEXIST") throw error;
			try {
				const age = Date.now() - statSync(lockPath).mtimeMs;
				// A crashed writer leaves the lock behind; reclaim it rather than
				// wedging the workspace forever.
				if (age > MANIFEST_LOCK_STALE_MS) {
					rmSync(lockPath, { force: true });
					continue;
				}
			} catch {
				continue;
			}
			if (Date.now() > deadline) {
				throw new Error(
					`Timed out waiting for the workspace manifest lock (${lockPath}). A writer is stuck mid-update; ` +
						`if no Unity work is running, delete that file and retry.`,
				);
			}
			await delay(25, options?.signal);
		}
	}
}

/**
 * Read-modify-write against on-disk state. Always prefer this over
 * readManifest+writeManifest: the mutate callback sees whatever landed in the
 * meantime, and nothing is written if it throws.
 */
export async function updateManifest<T>(
	manifestPath: string,
	mutate: (manifest: UnityWorkspaceManifest) => T,
	options?: { signal?: AbortSignal; timeoutMs?: number },
): Promise<T> {
	const lock = await acquireManifestLock(dirname(manifestPath), options);
	try {
		const manifest = readManifest(manifestPath);
		const result = mutate(manifest);
		writeManifest(manifestPath, manifest);
		return result;
	} finally {
		lock.release();
	}
}

export function loadWorkspaceManifest(workspacePath: string): UnityWorkspaceManifest {
	return readManifest(getManifestPath(workspacePath));
}

export async function releaseReservedIteration(manifestPath: string, reserved: number): Promise<void> {
	await updateManifest(manifestPath, (manifest) => {
		if (manifest.latestIteration === reserved) {
			manifest.latestIteration = Math.max(0, reserved - 1);
		}
	});
}

export function ensureWorkspaceScriptExists(workspacePath: string): string {
	const scriptPath = getWorkspaceScriptPath(workspacePath);
	if (!fileExists(scriptPath)) {
		writeFileSync(
			scriptPath,
			[
				"// pi Unity workspace script.",
				"// pi compiles this snippet into a temporary in-memory assembly and runs",
				"// `PiScript.Run`. The scene is saved afterwards when saveAfter is set.",
				"using UnityEditor;",
				"using UnityEngine;",
				"",
				"public static class PiScript",
				"{",
				"\tpublic static void Run()",
				"\t{",
				"\t\tDebug.Log(\"Hello from the pi Unity workspace.\");",
				"\t}",
				"}",
				"",
			].join("\n"),
			"utf8",
		);
	}
	return scriptPath;
}

export function ensureWorkspaceCritiqueLogExists(workspacePath: string): string {
	const logPath = getWorkspaceCritiqueLogPath(workspacePath);
	if (!fileExists(logPath)) writeFileSync(logPath, "", "utf8");
	return logPath;
}

/**
 * Installs the C# bridge plugin and the bridge-dir marker into a project.
 *
 * The marker matters: the plugin stays inert unless it can resolve a bridge
 * directory, so a project the user later opens by hand from the Hub (without
 * pi's env var) still finds the bridge instead of silently doing nothing.
 */
export function installBridgeIntoProject(projectPath: string, bridgeDir: string): void {
	const bridgeSource = getBundledUnityBridgeDir();
	if (!existsSync(bridgeSource)) {
		throw new Error(`Bundled Unity bridge plugin is missing: ${bridgeSource}`);
	}

	// A dedicated subdirectory, so a re-install can wipe exactly the plugin and
	// never touch the user's own Assets/Editor scripts. Chiffon already has
	// editor scripts in Assets/Imported, and blowing those away because pi
	// upgraded its plugin would be unacceptable.
	const bridgeTarget = join(projectPath, "Assets", "Editor", "PiUnityBridge");
	rmSync(bridgeTarget, { recursive: true, force: true });
	mkdirSync(dirname(bridgeTarget), { recursive: true });

	// Always refresh: pi owns these files, and a stale partial class would
	// silently run an older protocol against a newer pi -- or, worse, leave a
	// removed method behind and fail to compile at all.
	cpSync(bridgeSource, bridgeTarget, { recursive: true });

	writeFileSync(join(projectPath, BRIDGE_DIR_MARKER_FILE), `${bridgeDir}\n`, "utf8");
}

/**
 * A staged snippet's file name is `<prefix>-<epochMs>-<rand>.cs`, and NOTHING
 * removes it: one file accumulated per inlineCode call, forever.
 *
 * A scratch snippet is disposable by construction -- the code is also held in
 * the caller's hands, and the path is reported only so the caller can name it
 * -- so the bound is an age, not a liveness check, and it is applied when a
 * NEW one is staged rather than on a timer (there is no daemon here to hold a
 * timer, and the tool only runs when pi asks it to).
 *
 * The age is generous on purpose. The Editor reads the file once, at dispatch,
 * so anything younger than this could still be in flight on a slow run, and
 * deleting a snippet the Editor has not read yet turns a working call into a
 * "file not found". Past the bound the file has no reader left.
 *
 * Bounded by count as well as age, so a caller that never returns cannot grow
 * the directory without limit even inside one session, and so a burst of
 * snippets is cleaned up long before it is old.
 */
const SCRATCH_MAX_AGE_MS = 24 * 60 * 60 * 1000;
const SCRATCH_MAX_FILES = 200;
const SCRATCH_RE = /\.cs$/;

function pruneScratchFiles(dir: string, now: number): void {
	let entries: string[];
	try {
		entries = readdirSync(dir);
	} catch {
		return; // No dir yet: staging creates it.
	}

	const stale: { name: string; mtimeMs: number }[] = [];
	for (const name of entries) {
		if (!SCRATCH_RE.test(name)) continue;
		try {
			const mtimeMs = statSync(join(dir, name)).mtimeMs;
			// The age bound.
			if (now - mtimeMs > SCRATCH_MAX_AGE_MS) stale.push({ name, mtimeMs });
			else if (entries.length > SCRATCH_MAX_FILES) stale.push({ name, mtimeMs });
		} catch {
			// Unreadable entry: leave it. A prune that cannot stat a file is not
			// evidence the file is disposable.
		}
	}
	if (stale.length === 0) return;

	// Oldest first, so the count bound drops the stalest rather than whichever
	// happened to be listed first.
	stale.sort((a, b) => a.mtimeMs - b.mtimeMs);
	for (const entry of stale) {
		try {
			rmSync(join(dir, entry.name), { force: true });
		} catch {
			// Best-effort: a leftover scratch file is junk, not a failure worth
			// refusing the caller's own snippet over.
		}
	}
}

export function stageScratchFile(prefix: string, contents: string): string {
	const dir = getUnityTempDir();
	pruneScratchFiles(dir, Date.now());
	const path = join(dir, `${prefix}-${Date.now()}-${Math.random().toString(36).slice(2, 8)}.cs`);
	writeFileSync(path, contents, "utf8");
	return path;
}

export function normalizeWorkspacePath(cwd: string, workspace?: string): string {
	if (workspace?.trim()) return resolve(cwd, workspace.trim());
	return resolve(cwd, "outputs", createWorkspaceId());
}

