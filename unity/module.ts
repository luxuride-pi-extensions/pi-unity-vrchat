/**
 * unity_module_run / unity_module_revert.
 *
 * Multi-part work is split into modules so each part can be re-run and undone
 * independently, the same contract the Blender extension uses. The difference
 * in what gets checkpointed: a Unity "document" is the .unity scene file, so a
 * module checkpoint is a copy of the scene file rather than of the whole
 * project. That is a deliberate, smaller guarantee than Blender's model.blend
 * checkpoint: scripts that write assets under Assets/ are NOT rolled back by a
 * module revert, only scene state is. The revert result says so out loud
 * rather than implying a full undo.
 */

import { copyFileSync, existsSync, mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { join, resolve } from "node:path";

import { requestLiveUnityExecuteCSharp, requestLiveUnityReloadScene, requestLiveUnityRender } from "./bridge.js";
import { getManifestPath, loadWorkspaceManifest, updateManifest } from "./workspace.js";
import { releaseReservedIteration } from "./workspace.js";
import type { ModuleRunRecord } from "./workspace.js";

const MODULE_NAME_RE = /^[a-z0-9][a-z0-9-]{0,63}$/;
const MODULE_SCRIPT_FILE = "script.cs";
const MODULE_PREAMBLE_MARKER = "// --- pi-unity module preamble";
const RENDER_FILE = "render.png";

export interface ModuleRunOptions {
	cwd: string;
	workspace?: string;
	workspacePath?: string;
	moduleName: string;
	render?: boolean;
	view?: string;
	resolution?: { x: number; y: number };
	timeoutSeconds?: number;
}

export interface ModuleRunResult {
	workspacePath: string;
	moduleName: string;
	iteration: number;
	runDir: string;
	scriptPath: string;
	checkpointPath: string;
	scenePath: string;
	renderPath?: string;
	viewAdequacy: string;
}

function getModuleDir(workspacePath: string, moduleName: string): string {
	return join(workspacePath, "modules", moduleName);
}

function padRun(sequence: number): string {
	return String(sequence).padStart(2, "0");
}

/**
 * Prepends a contract header naming the workspace, scene, and module the script
 * belongs to. A worker's own traceback then names the contract it broke,
 * instead of pointing at a bare snippet.
 */
function buildModuleScriptPreamble(workspacePath: string, scenePath: string, moduleName: string): string {
	return [
		MODULE_PREAMBLE_MARKER,
		`// Generated by pi-unity. Edits below this line are preserved on re-run.`,
		`// WORKSPACE_PATH = ${JSON.stringify(workspacePath)}`,
		`// SCENE_PATH = ${JSON.stringify(scenePath)}`,
		`// MODULE_NAME = ${JSON.stringify(moduleName)}`,
		`//`,
		`// Rules: rebuild only what this module owns; never delete or rename another`,
		`// module's GameObjects. Guard with GameObject.Find so re-running is safe.`,
		"",
	].join("\n");
}

export async function unityModuleRun(options: ModuleRunOptions): Promise<ModuleRunResult> {
	const moduleName = options.moduleName.trim();
	if (!MODULE_NAME_RE.test(moduleName)) {
		throw new Error(
			`Invalid module name "${options.moduleName}". Use lowercase letters, digits, and dashes (max 64 chars), e.g. "table-top".`,
		);
	}

	const workspacePath = options.workspacePath ?? resolve(options.cwd, options.workspace ?? ".");
	const manifest = loadWorkspaceManifest(workspacePath);
	const moduleDir = getModuleDir(workspacePath, moduleName);
	const scriptPath = join(moduleDir, MODULE_SCRIPT_FILE);

	if (!existsSync(scriptPath)) {
		throw new Error(
			`Module script not found: ${scriptPath}. Write the module's C# script there first (worker agent), then run it.`,
		);
	}

	const manifestPath = getManifestPath(workspacePath);
	// Claim the iteration *and* the run sequence under one manifest write, and
	// publish it before the slow run starts: two concurrent runs must not be
	// handed the same iteration number.
	const claimed = await updateManifest<{ iteration: number; sequence: number }>(manifestPath, (state) => {
		const iteration = state.latestIteration + 1;
		state.latestIteration = iteration;
		const sequence = state.moduleRuns.length + 1;
		return { iteration, sequence };
	});

	const runDir = join(moduleDir, "runs", padRun(claimed.sequence));
	const rendersDir = join(runDir, "renders");
	mkdirSync(rendersDir, { recursive: true });
	const checkpointPath = join(runDir, `pre-${padRun(claimed.sequence)}.unity`);

	try {
		const source = readFileSync(scriptPath, "utf8");
		const preamble = buildModuleScriptPreamble(workspacePath, manifest.scenePath, moduleName);
		// Run a copy with the contract header, so re-running never rewrites the
		// worker's own file.
		const runScriptPath = join(runDir, MODULE_SCRIPT_FILE);
		if (source.includes(MODULE_PREAMBLE_MARKER)) writeFileSync(runScriptPath, source, "utf8");
		else writeFileSync(runScriptPath, `${preamble}${source}`, "utf8");

		// Checkpoint AFTER Unity saves the scene: the run itself saves with
		// saveAfter, so asking Unity to save first is what makes this copy the
		// true pre-run state.
		await requestLiveUnityExecuteCSharp({
			code: [
				"using UnityEditor;",
				"using UnityEditor.SceneManagement;",
				"public static class PiScript",
				"{",
				"\tpublic static void Run() { EditorSceneManager.SaveOpenScenes(); }",
				"}",
			].join("\n"),
			saveAfter: false,
			label: `module-save-before:${moduleName}`,
			timeoutMs: 60_000,
			launchProjectPath: manifest.projectPath,
		});

		const sceneFile = resolve(manifest.projectPath, manifest.scenePath);
		if (!existsSync(sceneFile)) {
			throw new Error(
				`The workspace scene file does not exist yet: ${sceneFile}. ` +
					`Save the scene in Unity once (File > Save As) so module checkpoints have something to copy.`,
			);
		}
		copyFileSync(sceneFile, checkpointPath);

		const result = await requestLiveUnityExecuteCSharp({
			code: readFileSync(runScriptPath, "utf8"),
			saveAfter: true,
			label: `module:${moduleName}`,
			timeoutMs: (options.timeoutSeconds ?? 180) * 1000,
			launchProjectPath: manifest.projectPath,
		});

		if (result.exitCode !== 0) {
			throw new Error(
				`Module "${moduleName}" failed (exit code ${result.exitCode}). The scene was NOT saved, this run was NOT ` +
					`recorded in moduleRuns, and there is nothing to revert. Script that ran: ${runScriptPath}. ` +
					`Output: ${result.stdout.trim() || "(none)"}`,
			);
		}

		let renderPath: string | undefined;
		let viewAdequacy = "Not requested.";
		if (options.render) {
			renderPath = join(moduleDir, RENDER_FILE);
			mkdirSync(join(moduleDir), { recursive: true });
			const rendered = await requestLiveUnityRender({
				outputPath: renderPath,
				width: options.resolution?.x ?? 960,
				height: options.resolution?.y ?? 540,
				cameraName: options.view,
				timeoutMs: 240_000,
			});
			viewAdequacy = rendered.usedActiveCamera
				? `Rendered with the active camera (${rendered.cameraName}).`
				: `Rendered with camera "${rendered.cameraName}".`;
		}

		// Publish the run record and the render output in one manifest write, so
		// a crash between the two cannot leave a revert target unrecorded.
		await updateManifest(manifestPath, (state) => {
			const record: ModuleRunRecord = {
				name: moduleName,
				iteration: claimed.iteration,
				checkpointPath,
				at: new Date().toISOString(),
				sequence: claimed.sequence,
				exitCode: result.exitCode,
				status: "ok",
			};
			state.moduleRuns.push(record);
			if (renderPath) state.renderOutputs.push(renderPath);
		});

		return {
			workspacePath,
			moduleName,
			iteration: claimed.iteration,
			runDir,
			scriptPath: runScriptPath,
			checkpointPath,
			scenePath: manifest.scenePath,
			renderPath,
			viewAdequacy,
		};
	} catch (error) {
		// Hand the iteration back so a failed attempt does not leave a gap that
		// looks like a lost render.
		await releaseReservedIteration(manifestPath, claimed.iteration);
		throw error;
	}
}

export interface ModuleRevertOptions {
	cwd: string;
	workspace?: string;
	workspacePath?: string;
	moduleName: string;
	iteration?: number;
	force?: boolean;
}

export interface ModuleRevertResult {
	workspacePath: string;
	moduleName: string;
	revertedTo: { iteration: number; checkpointPath: string; sequence: number };
	discardedLaterRuns: ModuleRunRecord[];
	warning?: string;
	liveUnityMessage?: string;
}

export async function unityModuleRevert(options: ModuleRevertOptions): Promise<ModuleRevertResult> {
	const workspacePath = options.workspacePath ?? resolve(options.cwd, options.workspace ?? ".");
	const manifest = loadWorkspaceManifest(workspacePath);
	const runs = manifest.moduleRuns.filter((run) => run.name === options.moduleName);

	if (runs.length === 0) {
		throw new Error(
			`Module "${options.moduleName}" has no recorded runs in ${workspacePath}, so there is nothing to revert. ` +
				`Reverts are only possible for runs recorded by unity_module_run.`,
		);
	}

	const target =
		options.iteration !== undefined
			? runs.find((run) => run.iteration === options.iteration)
			: runs[runs.length - 1];
	if (!target) {
		throw new Error(
			`Module "${options.moduleName}" has no run for iteration ${options.iteration}. ` +
				`Recorded iterations: ${runs.map((run) => run.iteration).join(", ")}`,
		);
	}

	// A revert rewrites shared scene state, so it must not silently discard
	// another module's work that landed afterwards.
	const laterRuns = manifest.moduleRuns.filter((run) => run.sequence > target.sequence);
	if (laterRuns.length > 0 && !options.force) {
		throw new Error(
			`Refusing to revert module "${options.moduleName}" iteration ${target.iteration}: ` +
				`${laterRuns.length} later module run(s) also modified the scene (${laterRuns.map((run) => `${run.name}#${run.iteration}`).join(", ")}). ` +
				`Reverting now would discard their work. Revert those modules first, or pass force: true to accept the loss.`,
		);
	}

	if (!existsSync(target.checkpointPath)) {
		throw new Error(
			`The checkpoint for module "${options.moduleName}" iteration ${target.iteration} is missing: ${target.checkpointPath}. ` +
				`The revert cannot be completed.`,
		);
	}

	const sceneFile = resolve(manifest.projectPath, manifest.scenePath);
	copyFileSync(target.checkpointPath, sceneFile);

	// Prune from on-disk state, not the snapshot taken before the copy.
	//
	// Only the MANIFEST is pruned. The run directories under
	// modules/<name>/runs/NN/ are deliberately left on disk: the checkpoint has
	// already been copied to the scene file by this point, but it is the only
	// way back if this revert turns out to have restored the wrong state, and
	// unity_module_revert can target an earlier iteration precisely because
	// those checkpoints survive. The manifest is the source of truth for what
	// is revertible; a leftover directory is inert, not misleading.
	await updateManifest(getManifestPath(workspacePath), (state) => {
		state.moduleRuns = state.moduleRuns.filter((run) => run.sequence < target.sequence);
	});

	let liveUnityMessage: string | undefined;
	try {
		await requestLiveUnityReloadScene();
	} catch (error) {
		// The file on disk is already correct; only the on-screen view is stale.
		liveUnityMessage =
			`The scene file was restored, but the live Unity Editor could not be told to reload it. ` +
			`Reload the scene manually (or reopen the project). Bridge said: ` +
			`${error instanceof Error ? error.message : String(error)}`;
	}

	return {
		workspacePath,
		moduleName: options.moduleName,
		revertedTo: {
			iteration: target.iteration,
			checkpointPath: target.checkpointPath,
			sequence: target.sequence,
		},
		discardedLaterRuns: laterRuns,
		warning: laterRuns.length > 0
			? `Discarded ${laterRuns.length} later run(s): ${laterRuns.map((run) => `${run.name}#${run.iteration}`).join(", ")}. ` +
				`Note: a module revert restores scene state only. Assets written under Assets/ by those runs were not rolled back.`
			: undefined,
		liveUnityMessage,
	};
}
